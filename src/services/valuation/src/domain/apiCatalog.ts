/**
 * A route prefix and the tag it belongs to.
 *
 * Matched longest-prefix-first, so `/api/v1/valuations/:id/payments` can belong
 * to Billing while everything else under `/api/v1/valuations` belongs to
 * Valuations. A prefix matches a path only at a segment boundary — `/api/v1/me`
 * does not swallow `/api/v1/metrics` — which is the bug this would otherwise
 * have shipped with, since the two differ after the shared prefix by a
 * character rather than by a slash.
 */
export interface ApiSection {
  prefix: string;
  tag: string;
  /** Declared but not rendered — see the Partner API note in the file docblock. */
  excluded?: true;
}


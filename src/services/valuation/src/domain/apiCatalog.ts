/**
 * OpenAPI 3.1 for the client/admin API, generated from the route table the
 * service actually registers.
 *
 * The partner API has had a spec since the round that built one from its
 * registry. The client API — 460-odd routes, everything the web app and the
 * firm workspace talk to — had nothing machine-readable at all. What stood in
 * for it was §2 of `docs/api-design.md`, which is a *design sketch* written
 * before the service existed: it lists paths without the `/api/v1` prefix they
 * ship under, names a handful of routes out of hundreds, and still describes an
 * AI provider that was removed. Nobody was misled by it for long, because
 * nobody could use it — but there was also nothing to import into a tool, no
 * way to answer "does this endpoint exist" without grepping, and no statement
 * anywhere of which routes are reachable without a session.
 *
 * ## What this document claims, and what it does not
 *
 * It is derived from `app.routeAudit`, so the *inventory* is exact and cannot
 * drift: every registered route appears, nothing that is not registered does,
 * and whether an operation requires a session is read from the preHandler
 * rather than from a list somebody maintains. The error half is equally real —
 * the responses come from `PROBLEM_CATALOG`, the same catalog the services
 * raise from and the published table renders from.
 *
 * What it does *not* claim is per-endpoint prose. There is no request or
 * response schema for these routes to derive one from: the client API validates
 * inside its handlers with zod rather than through fastify's `schema` option,
 * and a `summary` generated by rearranging the words already in the path would
 * be filler that reads like documentation. So prose lives at the tag level,
 * where it is written by hand and is true, and each operation carries what can
 * be stated exactly: its identifier, its tag, its path parameters, whether it
 * needs a session, and — for the unauthenticated ones — the reason from
 * `PUBLIC_ROUTES`, which is prose that already exists and is already reviewed.
 *
 * Writing that boundary down matters more than closing it. A spec that invents
 * a summary for every operation looks more complete and is less trustworthy,
 * because a reader cannot tell which sentences were written about the endpoint
 * and which were generated from its URL.
 *
 * The partner routes are excluded on purpose: they have a richer spec of their
 * own at `/api/partner/v1/openapi.json`, with request and response schemas, and
 * publishing a thinner second description of the same endpoints would give a
 * partner two documents to choose between. The section is still declared, so
 * the census below accounts for those routes rather than silently skipping
 * them.
 */


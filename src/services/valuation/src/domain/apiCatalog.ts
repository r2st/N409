/** Does `path` sit at or under `prefix`, at a segment boundary? */
export function underPrefix(path: string, prefix: string): boolean {
  if (prefix === '/') return path === '/';
  return path === prefix || path.startsWith(`${prefix}/`);
}

/**
 * The most specific section covering `path`, or undefined if none does — which
 * the census treats as a failure rather than as a default, so a new top-level
 * resource has to be placed rather than quietly landing in whatever tag sorts
 * first.
 */
export function sectionFor(path: string): ApiSection | undefined {
  let best: ApiSection | undefined;
  for (const section of API_SECTIONS) {
    if (!underPrefix(path, section.prefix)) continue;
    if (!best || section.prefix.length > best.prefix.length) best = section;
  }
  return best;
}

/** `METHOD /url` as the route audit spells it, split back into its halves. */
export function parseRouteKey(key: string): { method: string; path: string } {
  const cut = key.indexOf(' ');
  return { method: key.slice(0, cut), path: key.slice(cut + 1) };
}

/** `:id` → `{id}`, which is what OpenAPI templating wants. */
export function templatePath(path: string): string {
  return path.replace(/:([A-Za-z_][A-Za-z0-9_]*)/g, '{$1}');
}

const PROBLEM_REF = { $ref: '#/components/schemas/Problem' };

function problemResponse(type: string): Record<string, unknown> {
  const entry = PROBLEM_CATALOG[type];
  return {
    // Description straight from the catalog, so the spec's account of a failure
    // is the same sentence the published table gives and the same one the
    // `/api/v1/problems` endpoint serves. Three renderings, one source.
    description: entry ? `${entry.summary} ${entry.resolution}` : type,
    content: { 'application/problem+json': { schema: PROBLEM_REF } },
  };
}

/**
 * The problem document, as a component every operation references.
 *
 * Kept in step with the shared handler by `apiCatalog.test.ts`, which builds a
 * real `ApiProblem` body and checks every key it produces is declared here — a
 * spec that under-reports the error body is how a client ends up with no
 * generated type for `retry_after_seconds`, which is the one field a 429
 * handler needs.
 */
const PROBLEM_SCHEMA = {
  type: 'object',
  description:
    'RFC 9457 problem document. Every failure on this API uses this shape, served as ' +
    'application/problem+json. Branch on `type` — the vocabulary is at GET /api/v1/problems.',
  properties: {
    type: {
      type: 'string',
      description: 'Stable URN identifying the problem class. The only field to branch on.',
      enum: Object.keys(PROBLEM_CATALOG),
    },
    title: { type: 'string', description: 'Constant reason phrase for this type.' },
    status: { type: 'integer', description: 'HTTP status code, repeated in the body.' },
    detail: { type: 'string', description: 'Explanation specific to this occurrence. Absent on 5xx.' },
    instance: { type: 'string', description: 'The request path this failure occurred on.' },
    errors: {
      type: 'array',
      description: 'Field-level validation issues, present on 422 responses.',
      items: { type: 'object' },
    },
    retry_after_seconds: {
      type: 'integer',
      description: 'Seconds to wait before retrying. Mirrors the retry-after response header.',
    },
  },
  required: ['type', 'title', 'status'],
};

export interface ClientOpenApiInput {
  /** `METHOD /url` for every registered route — `app.routeAudit.all()`. */
  routes: readonly string[];
  /** The subset of those that run through `app.authenticate`. */
  authenticated: ReadonlySet<string>;
  /** Route key → why it is reachable without a session, from `PUBLIC_ROUTES`. */
  publicReasons: ReadonlyMap<string, string>;
  version: string;
}

/**
 * The generated document.
 *
 * Pure function of its input, so the route that serves it can rebuild per
 * request and never hold a stale copy — the same choice the partner spec makes,
 * and for the same reason.
 */
export function buildClientOpenApiDocument(input: ClientOpenApiInput): Record<string, unknown> {
  const paths: Record<string, Record<string, unknown>> = {};
  const usedTags = new Set<string>();

  for (const key of input.routes) {
    const { method, path } = parseRouteKey(key);
    const section = sectionFor(path);
    if (!section || section.excluded) continue;
    usedTags.add(section.tag);

    const authenticated = input.authenticated.has(key);
    const reason = input.publicReasons.get(key);
    const parameters = pathParameters(templatePath(path)).map((name) => ({
      name,
      in: 'path',
      required: true,
      schema: { type: 'string' },
      description: `Identifier from a previous response (${name}).`,
    }));

    const operation: Record<string, unknown> = {
      operationId: operationId(method, templatePath(path)),
      tags: [section.tag],
      ...(parameters.length > 0 ? { parameters } : {}),
      // Only for the public routes, where `PUBLIC_ROUTES` already carries a
      // reviewed sentence about why no session is needed. Everywhere else the
      // operation says nothing rather than saying something generated.
      ...(reason ? { description: `Reachable without a session: ${reason}.` } : {}),
      responses: {
        '2XX': { description: 'Success. Response bodies are not described by this document.' },
        ...(authenticated
          ? {
              '401': problemResponse('urn:n409:problem:unauthorized'),
              '403': problemResponse('urn:n409:problem:forbidden'),
            }
          : {}),
        '404': problemResponse('urn:n409:problem:not-found'),
        '422': problemResponse('urn:n409:problem:validation'),
        '429': problemResponse('urn:n409:problem:rate-limited'),
        '500': problemResponse('urn:n409:problem:internal'),
      },
      // `security: []` is not the same as omitting the key: it explicitly clears
      // the document-level requirement, which is how a public route is marked.
      security: authenticated ? [{ session: [] }, { bearer: [] }] : [],
    };

    const templated = templatePath(path);
    paths[templated] ??= {};
    paths[templated]![method.toLowerCase()] = operation;
  }

  return {
    openapi: '3.1.0',
    info: {
      title: 'N409 Client API',
      version: input.version,
      description:
        'Every endpoint the web application and the firm workspace call. Generated from the route ' +
        'table this service registers, so the inventory is exact; request and response bodies are ' +
        'validated inside the handlers rather than by a route schema, so this document describes ' +
        'them only at the tag level. Failures are uniform — an RFC 9457 problem document whose ' +
        '`type` vocabulary is served at GET /api/v1/problems. The partner API is documented ' +
        'separately, with full schemas, at /api/partner/v1/openapi.json.',
    },
    servers: [{ url: '/' }],
    tags: API_TAGS.filter((tag) => usedTags.has(tag.name)),
    components: {
      securitySchemes: {
        session: {
          type: 'apiKey',
          in: 'cookie',
          name: SESSION_COOKIE,
          description: 'Session cookie set by POST /api/v1/auth/login.',
        },
        bearer: {
          type: 'http',
          scheme: 'bearer',
          bearerFormat: 'JWT',
          description: 'The same session as a bearer token, for non-browser clients.',
        },
      },
      schemas: { Problem: PROBLEM_SCHEMA },
    },
    security: [{ session: [] }, { bearer: [] }],
    paths,
  };
}
